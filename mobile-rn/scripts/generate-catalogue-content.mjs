/**
 * Builds the RN copy of the exercise catalogue text and media map.
 *
 * Run from `mobile-rn/`:
 *   node scripts/generate-catalogue-content.mjs
 *
 * The media map keeps one static `require` per catalogue file, because Metro
 * cannot resolve a dynamic path. The files stay in `catalogue/media`; the RN
 * project watches that folder instead of copying ~200 MB into a second tree.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXDB } from '../../frontend/src/lib/exercises-data.js';
import zhLocale from '../../frontend/src/locales/zh.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const catalogueDir = join(root, 'catalogue');
const outDir = resolve(here, '../src');
const zhPath = join(catalogueDir, 'i18n', 'zh.json');
const exercisesDir = join(catalogueDir, 'exercises');

const zh = JSON.parse(readFileSync(zhPath, 'utf8'));
const bodyPartZh = {
  back: '背部',
  cardio: '有氧',
  chest: '胸部',
  'full body': '全身',
  'lower arms': '前臂',
  'lower legs': '小腿',
  neck: '颈部',
  shoulders: '肩部',
  'upper arms': '上臂',
  'upper legs': '大腿',
  waist: '腰腹',
};
const muscleZh = key => zhLocale[key] ?? key;

const english = new Map();
for (const name of readdirSync(exercisesDir)) {
  if (!name.endsWith('.json')) continue;
  const entry = JSON.parse(readFileSync(join(exercisesDir, name), 'utf8'));
  english.set(entry.id, entry);
}

const content = {};
let withChineseInstructions = 0;
let withChineseName = 0;
for (const exercise of EXDB) {
  const id = exercise.id;
  const en = english.get(id);
  const translated = zh[id];
  const name = translated?.name ?? exercise.n;
  if (translated?.name) withChineseName++;
  const instructions = translated?.instructions ?? en?.instructions ?? [];
  if (translated?.instructions) withChineseInstructions++;

  let description = translated?.description;
  if (!description) {
    const target = muscleZh(exercise.tg ?? en?.target ?? '');
    const secondary = (exercise.sm ?? en?.secondaryMuscles ?? [])
      .filter(muscle => muscle !== exercise.tg && muscle !== en?.target)
      .map(muscleZh)
      .slice(0, 3);
    const body = bodyPartZh[exercise.bp] ?? exercise.bp;
    description = target
      ? `${body}动作，主要训练${target}${secondary.length ? `，并参与${secondary.join('、')}` : ''}。`
      : `${body}动作。`;
  }

  content[id] = {
    name,
    description,
    instructions,
    bodyPart: exercise.bp,
    equipment: exercise.eq,
    target: muscleZh(exercise.tg ?? en?.target ?? ''),
    secondary: (exercise.sm ?? en?.secondaryMuscles ?? []).map(muscleZh),
    instructionsSource: translated?.instructions ? 'zh' : 'en',
  };
}

writeFileSync(join(outDir, 'catalogueContent.generated.json'), JSON.stringify(content));
console.log(`content: ${Object.keys(content).length} exercises (${withChineseName} names, ${withChineseInstructions} Chinese instruction sets)`);

const still = [];
const clips = [];
const skipClips = process.env.SKIP_CLIPS === '1';
for (const exercise of EXDB) {
  const image = join(catalogueDir, 'media', 'still', exercise.img ?? `${exercise.id}.webp`);
  const clip = join(catalogueDir, 'media', 'clip', exercise.gif ?? `${exercise.id}.mp4`);
  if (existsSync(image)) still.push([exercise.id, `../../catalogue/media/still/${exercise.img ?? `${exercise.id}.webp`}`]);
  if (!skipClips && existsSync(clip)) clips.push([exercise.id, `exercise-media/clip/${exercise.gif ?? `${exercise.id}.mp4`}`]);
}

const requireMap = (name, entries) => {
  const lines = entries.map(([id, path]) => `  '${id}': require('${path}'),`);
  return `// Generated by scripts/generate-catalogue-content.mjs. Do not edit.\n`
    + `export const ${name}: Record<string, number> = {\n${lines.join('\n')}\n};\n`;
};
const stringMap = (name, entries) => {
  const lines = entries.map(([id, path]) => `  '${id}': '${path}',`);
  return `// Generated by scripts/generate-catalogue-content.mjs. Do not edit.\n`
    + `export const ${name}: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
};
writeFileSync(join(outDir, 'catalogueMedia.generated.ts'),
  requireMap('CATALOGUE_STILL', still) + '\n' + stringMap('CATALOGUE_CLIPS', clips));
console.log(`media: ${still.length} bundled stills, ${clips.length} staged clips`);
