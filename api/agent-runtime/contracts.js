/* Shared agent runtime contracts.
 *
 * Plain JS on purpose: the same file runs in Node and in Metro without a
 * runtime dependency. The TypeScript shape lives in contracts.d.ts.
 */

export const AGENT_SCHEMA_VERSION = 1;

export const RUN_STATUSES = Object.freeze([
  'accepted',
  'running',
  'completed',
  'failed',
  'cancelled',
  'interrupted',
]);

export const TERMINAL_STATUSES = Object.freeze([
  'completed',
  'failed',
  'cancelled',
  'interrupted',
]);

export const MEMORY_CATEGORIES = Object.freeze([
  'preference',
  'goal',
  'constraint',
  'note',
]);

export const EXECUTION_LOCATIONS = Object.freeze(['local', 'server']);

export const isTerminalStatus = status => TERMINAL_STATUSES.includes(status);

export const isRunStatus = status => RUN_STATUSES.includes(status);

export const isMemoryCategory = value => MEMORY_CATEGORIES.includes(value);

/** A request id has to be long enough to deduplicate and short enough to store. */
export const validRequestId = value =>
  typeof value === 'string' && /^[A-Za-z0-9_-]{8,128}$/.test(value);

/** Profile ids are generated by the host but never trusted from a model. */
export const validProfileId = value =>
  typeof value === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(value);

/** A task id is a stable namespace such as `stub.v1`. */
export const validTaskId = value =>
  typeof value === 'string' && /^[A-Za-z0-9_.-]{1,64}$/.test(value);

export const RUN_DEFAULTS = Object.freeze({
  rounds: 3,
  toolCalls: 8,
  contextChars: 24000,
  historyItems: 8,
  memoryItems: 8,
  attachments: 4,
  attachmentBytes: 2 * 1024 * 1024,
});

export function withRunDefaults(budgets = {}) {
  const out = { ...RUN_DEFAULTS };
  for (const [key, value] of Object.entries(budgets || {})) {
    if (value === undefined || value === null) continue;
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
      throw new Error(`agent budget ${key} must be a non-negative number`);
    }
    out[key] = Math.floor(value);
  }
  return out;
}
